CREATE DATABASE IF NOT EXISTS forme CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE forme;
CREATE TABLE IF NOT EXISTS users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE, password_hash VARCHAR(255) NOT NULL,
 role ENUM('customer','admin') NOT NULL DEFAULT 'customer', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS addresses (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id INT UNSIGNED NOT NULL,
 label VARCHAR(60) NOT NULL, recipient VARCHAR(100) NOT NULL, phone VARCHAR(30) NOT NULL,
 line1 VARCHAR(255) NOT NULL, city VARCHAR(100) NOT NULL, postcode VARCHAR(10) NOT NULL,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS categories (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, department ENUM('Women','Men','Kids') NOT NULL,
 name VARCHAR(80) NOT NULL, image VARCHAR(255) NOT NULL, UNIQUE KEY(department,name)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS products (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, category_id INT UNSIGNED NOT NULL,
 name VARCHAR(150) NOT NULL, price DECIMAL(10,2) NOT NULL, description TEXT NOT NULL,
 material VARCHAR(255) NOT NULL, featured TINYINT(1) NOT NULL DEFAULT 0,
 active TINYINT(1) NOT NULL DEFAULT 1, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(category_id) REFERENCES categories(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS variants (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, product_id INT UNSIGNED NOT NULL,
 color VARCHAR(60) NOT NULL, hex CHAR(7) NOT NULL, size VARCHAR(10) NOT NULL,
 sku VARCHAR(80) NOT NULL UNIQUE, stock INT UNSIGNED NOT NULL DEFAULT 0,
 image VARCHAR(255) NOT NULL,
 UNIQUE KEY(product_id,color,size), FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS product_images (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, product_id INT UNSIGNED NOT NULL,
 color VARCHAR(60) NOT NULL, image VARCHAR(255) NOT NULL,
 FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS banners (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, placement ENUM('hero','campaign') NOT NULL,
 title VARCHAR(150) NOT NULL, subtitle VARCHAR(255) NOT NULL, image VARCHAR(255) NOT NULL,
 mobile_image VARCHAR(255) DEFAULT NULL, text_color CHAR(7) NOT NULL DEFAULT '#FFFFFF',
 alignment ENUM('left','center','right') NOT NULL DEFAULT 'left',
 button_text VARCHAR(60) NOT NULL, link VARCHAR(255) NOT NULL,
 sort_order INT NOT NULL DEFAULT 0, active TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS cart_items (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id INT UNSIGNED NOT NULL,
 variant_id INT UNSIGNED NOT NULL, quantity INT UNSIGNED NOT NULL,
 UNIQUE KEY(user_id,variant_id), FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(variant_id) REFERENCES variants(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS wishlist (
 user_id INT UNSIGNED NOT NULL, product_id INT UNSIGNED NOT NULL,
 PRIMARY KEY(user_id,product_id), FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS orders (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id INT UNSIGNED NOT NULL,
 reference VARCHAR(40) NOT NULL UNIQUE, recipient VARCHAR(100) NOT NULL, phone VARCHAR(30) NOT NULL,
 address VARCHAR(500) NOT NULL, subtotal DECIMAL(10,2) NOT NULL, shipping DECIMAL(10,2) NOT NULL,
 total DECIMAL(10,2) NOT NULL, status ENUM('Confirmed','Processing','Shipped','Completed','Cancelled') NOT NULL DEFAULT 'Confirmed',
 payment_status ENUM('Simulated paid') NOT NULL DEFAULT 'Simulated paid',
 checkout_key VARCHAR(64) NOT NULL UNIQUE, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS order_items (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_id INT UNSIGNED NOT NULL,
 variant_id INT UNSIGNED DEFAULT NULL, product_id INT UNSIGNED DEFAULT NULL,
 name VARCHAR(150) NOT NULL, color VARCHAR(60) NOT NULL, size VARCHAR(10) NOT NULL,
 image VARCHAR(255) NOT NULL, unit_price DECIMAL(10,2) NOT NULL, quantity INT UNSIGNED NOT NULL,
 FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE CASCADE,
 FOREIGN KEY(variant_id) REFERENCES variants(id) ON DELETE SET NULL,
 FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE SET NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS reviews (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id INT UNSIGNED NOT NULL,
 product_id INT UNSIGNED NOT NULL, rating TINYINT UNSIGNED NOT NULL, comment VARCHAR(1500) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, UNIQUE KEY(user_id,product_id),
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS settings (
 setting_key VARCHAR(60) PRIMARY KEY, setting_value VARCHAR(255) NOT NULL
) ENGINE=InnoDB;
