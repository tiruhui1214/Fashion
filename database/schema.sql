CREATE DATABASE IF NOT EXISTS forme CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE forme;
CREATE TABLE IF NOT EXISTS users (
 phone VARCHAR(30) NOT NULL DEFAULT '',
 active TINYINT(1) NOT NULL DEFAULT 1,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE, password_hash VARCHAR(255) NOT NULL,
 role ENUM('customer','admin') NOT NULL DEFAULT 'customer', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS addresses (
 line2 VARCHAR(255) NOT NULL DEFAULT '',
 state VARCHAR(100) NOT NULL DEFAULT '',
 country VARCHAR(60) NOT NULL DEFAULT 'Malaysia',
 is_default TINYINT(1) NOT NULL DEFAULT 0,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id INT UNSIGNED NOT NULL,
 label VARCHAR(60) NOT NULL, recipient VARCHAR(100) NOT NULL, phone VARCHAR(30) NOT NULL,
 line1 VARCHAR(255) NOT NULL, city VARCHAR(100) NOT NULL, postcode VARCHAR(10) NOT NULL,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS categories (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, department ENUM('Women','Men','Kids') NOT NULL,
 name VARCHAR(80) NOT NULL, image VARCHAR(255) NOT NULL, UNIQUE KEY(department,name)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS products (
 CONSTRAINT products_creator_fk FOREIGN KEY(created_by_admin_id) REFERENCES users(id) ON DELETE SET NULL,
 style VARCHAR(255) NOT NULL DEFAULT '',
 occasion VARCHAR(255) NOT NULL DEFAULT '',
 created_by_admin_id INT UNSIGNED DEFAULT NULL,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, category_id INT UNSIGNED NOT NULL,
 name VARCHAR(150) NOT NULL, price DECIMAL(10,2) NOT NULL, description TEXT NOT NULL,
 material VARCHAR(255) NOT NULL, featured TINYINT(1) NOT NULL DEFAULT 0,
 active TINYINT(1) NOT NULL DEFAULT 1, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(category_id) REFERENCES categories(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS variants (
 minimum_stock_level INT UNSIGNED NOT NULL DEFAULT 5,
 active TINYINT(1) NOT NULL DEFAULT 1,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, product_id INT UNSIGNED NOT NULL,
 color VARCHAR(60) NOT NULL, hex CHAR(7) NOT NULL, size VARCHAR(10) NOT NULL,
 sku VARCHAR(80) NOT NULL UNIQUE, stock INT UNSIGNED NOT NULL DEFAULT 0,
 image VARCHAR(255) NOT NULL,
 UNIQUE KEY(product_id,color,size), FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS product_images (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, product_id INT UNSIGNED NOT NULL,
 color VARCHAR(60) NOT NULL, image VARCHAR(255) NOT NULL,
 FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS banners (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, placement ENUM('hero','campaign') NOT NULL,
 title VARCHAR(150) NOT NULL, subtitle VARCHAR(255) NOT NULL, image VARCHAR(255) NOT NULL,
 mobile_image VARCHAR(255) DEFAULT NULL, text_color CHAR(7) NOT NULL DEFAULT '#FFFFFF',
 alignment ENUM('left','center','right') NOT NULL DEFAULT 'left',
 button_text VARCHAR(60) NOT NULL, link VARCHAR(255) NOT NULL,
 sort_order INT NOT NULL DEFAULT 0, active TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS cart_items (
 is_selected TINYINT(1) NOT NULL DEFAULT 1,
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id INT UNSIGNED NOT NULL,
 variant_id INT UNSIGNED NOT NULL, quantity INT UNSIGNED NOT NULL,
 UNIQUE KEY(user_id,variant_id), FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(variant_id) REFERENCES variants(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS wishlist (
 user_id INT UNSIGNED NOT NULL, product_id INT UNSIGNED NOT NULL,
 PRIMARY KEY(user_id,product_id), FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS promotions (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 created_by_admin_id INT UNSIGNED NOT NULL,
 promo_code VARCHAR(40) NOT NULL UNIQUE,
 discount_rate DECIMAL(5,2) NOT NULL,
 minimum_purchase_amount DECIMAL(10,2) NOT NULL DEFAULT 0.00,
 start_date DATETIME NOT NULL,
 end_date DATETIME NOT NULL,
 active TINYINT(1) NOT NULL DEFAULT 1,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT promotions_creator_fk FOREIGN KEY(created_by_admin_id) REFERENCES users(id),
 CONSTRAINT promotions_rate_check CHECK(discount_rate > 0 AND discount_rate <= 100),
 CONSTRAINT promotions_minimum_check CHECK(minimum_purchase_amount >= 0),
 CONSTRAINT promotions_dates_check CHECK(end_date >= start_date)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS orders (
 CONSTRAINT orders_admin_fk FOREIGN KEY(last_status_updated_by_admin_id) REFERENCES users(id) ON DELETE SET NULL,
 CONSTRAINT orders_address_fk FOREIGN KEY(shipping_address_id) REFERENCES addresses(id) ON DELETE SET NULL,
 shipping_address_id INT UNSIGNED DEFAULT NULL,
 last_status_updated_by_admin_id INT UNSIGNED DEFAULT NULL,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id INT UNSIGNED NOT NULL,
 reference VARCHAR(40) NOT NULL UNIQUE, recipient VARCHAR(100) NOT NULL, phone VARCHAR(30) NOT NULL,
 address VARCHAR(500) NOT NULL, subtotal DECIMAL(10,2) NOT NULL, shipping DECIMAL(10,2) NOT NULL,
 total DECIMAL(10,2) NOT NULL,
 promotion_id INT UNSIGNED DEFAULT NULL,
 promo_code_used VARCHAR(40) DEFAULT NULL,
 discount_amount DECIMAL(10,2) NOT NULL DEFAULT 0.00,
 CONSTRAINT orders_promotion_fk FOREIGN KEY(promotion_id) REFERENCES promotions(id) ON DELETE SET NULL,
 status ENUM('Confirmed','Processing','Shipped','Completed','Cancelled') NOT NULL DEFAULT 'Confirmed',
 payment_status ENUM('Simulated paid') NOT NULL DEFAULT 'Simulated paid',
 checkout_key VARCHAR(64) NOT NULL UNIQUE, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS order_items (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_id INT UNSIGNED NOT NULL,
 variant_id INT UNSIGNED DEFAULT NULL, product_id INT UNSIGNED DEFAULT NULL,
 name VARCHAR(150) NOT NULL, color VARCHAR(60) NOT NULL, size VARCHAR(10) NOT NULL,
 image VARCHAR(255) NOT NULL, unit_price DECIMAL(10,2) NOT NULL, quantity INT UNSIGNED NOT NULL,
 FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE CASCADE,
 FOREIGN KEY(variant_id) REFERENCES variants(id) ON DELETE SET NULL,
 FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE SET NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS reviews (
 customer_deleted TINYINT(1) NOT NULL DEFAULT 0,
 CONSTRAINT reviews_moderator_fk FOREIGN KEY(moderated_by_admin_id) REFERENCES users(id) ON DELETE SET NULL,
 is_hidden TINYINT(1) NOT NULL DEFAULT 0,
 moderated_by_admin_id INT UNSIGNED DEFAULT NULL,
 moderated_at DATETIME DEFAULT NULL,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id INT UNSIGNED NOT NULL,
 product_id INT UNSIGNED NOT NULL, rating TINYINT UNSIGNED NOT NULL, comment VARCHAR(1500) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, UNIQUE KEY(user_id,product_id),
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS settings (
 setting_key VARCHAR(60) PRIMARY KEY, setting_value VARCHAR(255) NOT NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS payments (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 order_id INT UNSIGNED NOT NULL UNIQUE,
 payment_method VARCHAR(40) NOT NULL DEFAULT 'Simulated',
 amount DECIMAL(10,2) NOT NULL,
 payment_status VARCHAR(40) NOT NULL DEFAULT 'Simulated paid',
 payment_reference VARCHAR(80) NOT NULL UNIQUE,
 paid_at DATETIME NOT NULL,
 FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS order_status_history (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 order_id INT UNSIGNED NOT NULL,
 actor_user_id INT UNSIGNED DEFAULT NULL,
 from_status VARCHAR(30) DEFAULT NULL,
 to_status VARCHAR(30) NOT NULL,
 changed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE CASCADE,
 FOREIGN KEY(actor_user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;

